'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('qplay', {
  isElectron: true,
  platform: process.platform,
  openShow: () => ipcRenderer.invoke('show:open'),
  readShow: (p) => ipcRenderer.invoke('show:read', p),
  saveShow: (path, data, saveAs) => ipcRenderer.invoke('show:save', { path, data, saveAs }),
  exportPackage: (data) => ipcRenderer.invoke('show:export-package', { data }),
  exportText: (name, text, ext, label) => ipcRenderer.invoke('file:export-text', { name, text, ext, label }),
  launchFile: () => ipcRenderer.invoke('show:launch-file'),
  chooseMedia: (kind) => ipcRenderer.invoke('media:choose', kind),
  filesExist: (paths) => ipcRenderer.invoke('media:exists', paths),
  reveal: (p) => ipcRenderer.invoke('media:reveal', p),
  pathForFile: (file) => webUtils.getPathForFile(file),
  mediaUrl: (p) => 'qp://app/__media/' + encodeURIComponent(p),
  nameOf: (p) => String(p || '').split(/[\\/]/).pop(),
  listDisplays: () => ipcRenderer.invoke('displays:list'),
  placeVideo: (prefs) => ipcRenderer.invoke('video:place', prefs),
  oscListen: (port) => ipcRenderer.invoke('osc:listen', port),
  oscSend: (msg) => ipcRenderer.invoke('osc:send', msg),
  onOsc: (cb) => ipcRenderer.on('osc:message', (_e, m) => cb(m)),
  onMenu: (cb) => ipcRenderer.on('menu', (_e, cmd, arg) => cb(cmd, arg)),
  onVideoClosed: (cb) => ipcRenderer.on('video:closed', (_e, name) => cb(name)),
  onDisplaysChanged: (cb) => ipcRenderer.on('displays:changed', () => cb()),
  setDirty: (v) => ipcRenderer.send('app:dirty', v),
  setTitle: (t) => ipcRenderer.send('app:title', t),
  nativeEdit: (cmd) => ipcRenderer.send('edit:native', cmd),
  saveRecovery: (data, path) => ipcRenderer.invoke('recovery:save', { data, path }),
  getRecovery: () => ipcRenderer.invoke('recovery:get'),
  clearRecovery: () => ipcRenderer.invoke('recovery:clear'),
  relink: (names) => ipcRenderer.invoke('media:relink', names),
  lookup: (host) => ipcRenderer.invoke('net:lookup', host),
  logAppend: (line) => ipcRenderer.send('log:append', line),
  openLogFolder: () => ipcRenderer.invoke('log:folder'),
  dmxSend: (msg) => ipcRenderer.send('dmx:send', msg),
  scriptStatus: () => ipcRenderer.invoke('script:status'),
  scriptAllow: (on) => ipcRenderer.invoke('script:allow', on),
  scriptRun: (s) => ipcRenderer.invoke('script:run', s),
  printPdf: (html, name) => ipcRenderer.invoke('print:pdf', { html, name }),
  cameraAccess: () => ipcRenderer.invoke('media:camera-access'),
  remoteStart: (opts) => ipcRenderer.invoke('remote:start', opts),
  remotePublish: (state) => ipcRenderer.send('remote:publish', state),
  onRemoteCmd: (cb) => ipcRenderer.on('remote:cmd', (_e, cmd, arg, from) => cb(cmd, arg, from)),
  openStageManager: () => ipcRenderer.invoke('sm:open'),
  historyList: (showPath) => ipcRenderer.invoke('history:list', showPath),
  historyRead: (file, showPath) => ipcRenderer.invoke('history:read', file, showPath),
  saveRecording: (name, bytes, showPath) => ipcRenderer.invoke('rec:save', { name, bytes, showPath }),
  collabPublish: (payload) => ipcRenderer.send('collab:publish', payload),
  collabPresence: (p) => ipcRenderer.invoke('collab:presence', p),
  onCollabIncoming: (cb) => ipcRenderer.on('collab:incoming', (_e, msg) => cb(msg)),
  collabFetch: (req) => ipcRenderer.invoke('collab:fetch', req),
  collabListen: (req) => ipcRenderer.invoke('collab:listen', req),
  onCollabEvent: (cb) => ipcRenderer.on('collab:event', (_e, ev) => cb(ev)),
  openUrl: (u) => ipcRenderer.send('shell:open-url', u),
  rtcToClient: (id, msg) => ipcRenderer.send('rtc:to-client', { id, msg }),
  rtcSetInfo: (info) => ipcRenderer.send('rtc:info', info),
  onRtcSignal: (cb) => ipcRenderer.on('rtc:signal', (_e, m) => cb(m)),
  outputSourceId: (frame) => ipcRenderer.invoke('output:source-id', frame),
  appControl: (req) => ipcRenderer.invoke('app:control', req),
  telnetSend: (req) => ipcRenderer.invoke('telnet:send', req),
  screenshot: (req) => ipcRenderer.invoke('output:screenshot', req),
  screenshotDir: () => ipcRenderer.invoke('shot:default-dir'),
  openShotFolder: (dir) => ipcRenderer.invoke('shot:open-folder', dir),
  chooseFolder: (opts) => ipcRenderer.invoke('dialog:folder', opts),
  closeNow: () => ipcRenderer.send('app:close-now'),
});
